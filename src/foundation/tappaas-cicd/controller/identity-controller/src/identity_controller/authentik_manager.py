@dataclass
class AuthentikConfig:
    """Connection settings for the Authentik admin API."""

    base_url: str               # e.g. "http://identity.mgmt.internal:9000"
    token: str
    verify_tls: bool = True
    timeout: float = 30.0

    @property
    def api(self) -> str:
        return f"{self.base_url.rstrip('/')}/api/v3"


@dataclass
class ProxyApp:
    """A forward-auth Authentik Application + Proxy Provider pair (Phase C)."""

    name: str                   # human-readable, used as Application name
    slug: str                   # URL slug (must match across runs for idempotency)
    external_host: str          # public URL of the protected service, e.g. https://openwebui.test.tapaas.org
    description: str = ""
    # Where Authentik's application list opens the app. Empty: external_host.
    # "blank://blank" hides the app from the list -- for a gate whose module
    # shows its own tile through an OIDC app (#806).
    launch_url: str = ""


@dataclass
class OidcApp:
    """An OIDC Application + Provider pair (ADR-006 — Nextcloud & other OIDC apps)."""

    name: str
    slug: str
    redirect_uris: list[str]
    # Scope-mapping NAMES the provider should expose. The default set is enough
    # for login + group sync: Authentik's stock ``profile`` scope already emits a
    # ``groups`` claim, so Nextcloud's ``--mapping-groups=groups`` works without a
    # custom scope. Unknown names are skipped with a warning.
    scopes: list[str] | None = None
    description: str = ""
    # Where Authentik's application list (My applications) opens the app. Empty:
    # left as it is, and Authentik falls back to the first redirect URI's origin
    # -- the app's front page, i.e. its own login screen. Set to the app's
    # SSO entry point, the user who clicks it in Authentik goes straight in.
    launch_url: str = ""


@dataclass
class OidcAppResult:
    """OIDC provider + application identifiers returned after ensure.

    ``client_id`` / ``client_secret`` are read back from Authentik (the secret is
    auto-generated on create and preserved across idempotent re-runs). The caller
    builds the discovery URL from the PUBLIC identity URL + slug:
    ``<public>/application/o/<slug>/.well-known/openid-configuration``.
    """

    application_pk: str
    provider_pk: int
    slug: str
    client_id: str
    client_secret: str


DEFAULT_OIDC_SCOPES = ["openid", "email", "profile"]
# The grants an OIDC login needs. Since Authentik 2026.8 a provider carries its
# own allowed grant list, and the model's default is EMPTY: a provider created
# through the API without it cannot run any flow, and the login fails at the
# authorize step with "invalid_request" ("Invalid grant_type for provider"). An
# existing provider keeps whatever it already allows; these two are added to it.
OIDC_LOGIN_GRANT_TYPES = ["authorization_code", "refresh_token"]

# Authentik 2025.10 changed the stock ``email`` scope's ``email_verified`` from
# true to false (#748). TAPPaaS users' addresses are set by the operator through
# identity-manager — nobody self-registers — so they are verified by
# construction, and a client that matches accounts by email (openwebui's
# OAUTH_MERGE_ACCOUNTS_BY_EMAIL) keeps working. This mapping takes the stock
# one's place on every OIDC provider.
EMAIL_VERIFIED_MAPPING = "tappaas: OpenID 'email' (verified)"
EMAIL_VERIFIED_EXPRESSION = 'return {"email": request.user.email, "email_verified": True}'


@dataclass
class ProxyAppResult:
    """Provider + application PKs returned after ensure."""

    application_pk: str         # core.Application primary key (UUID)
    provider_pk: int            # providers.proxy primary key (int)
    slug: str


class AuthentikManager:
    """Idempotent admin-API client for Authentik."""

    def __init__(self, config: AuthentikConfig):
        self.config = config
        self._client: httpx.Client | None = None
        # Per-instance flow-slug → pk cache (avoid sharing across managers).
        self._flow_cache: dict[str, str] = {}
        self._version: str | None = None

    def connect(self) -> "AuthentikManager":
        self._client = httpx.Client(
            base_url=self.config.api,
            # No default Content-Type: httpx sets application/json for a json=
            # body itself, and a default here overrode the multipart type of a
            # file upload (415 from /admin/file/, #479).
            headers={
                "Authorization": f"Bearer {self.config.token}",
                "Accept": "application/json",
            },
            timeout=self.config.timeout,
            verify=self.config.verify_tls,
        )
        return self

    def disconnect(self):
        if self._client is not None:
            self._client.close()
        self._client = None

    def __enter__(self) -> "AuthentikManager":
        return self.connect()

    def __exit__(self, exc_type, exc_val, exc_tb):
        self.disconnect()

    @property
    def client(self) -> httpx.Client:
        if not self._client:
            raise RuntimeError("Not connected. Use connect() or context manager.")
        return self._client

    # ── primitives ──────────────────────────────────────────────────────

    def server_version(self) -> str | None:
        """The running Authentik version ("2025.2.1"), or None if it cannot be read.

        The API changes shape across release lines (#748), and a site walks them
        one per update, so the client asks rather than assumes."""
        if self._version is None:
            try:
                self._version = str(self._get_json("/admin/version/").get("version_current") or "")
            except Exception:
                self._version = ""
        return self._version or None

    def _at_least(self, version: str) -> bool:
        """True when the server runs ``version`` or later (YYYY.M[.P])."""
        have = self.server_version()
        if not have:
            return False
        def key(v: str) -> tuple:
            return tuple(int(p) for p in (v.split(".") + ["0", "0"])[:3] if p.isdigit())
        return key(have) >= key(version)

    def _get_json(self, path: str, **params) -> dict:
        r = self.client.get(path, params=params)
        r.raise_for_status()
        return r.json()

    def _post_json(self, path: str, body: dict) -> dict:
        r = self.client.post(path, json=body)
        r.raise_for_status()
        return r.json()

    def _patch_json(self, path: str, body: dict) -> dict:
        r = self.client.patch(path, json=body)
        r.raise_for_status()
        return r.json()

    def _delete(self, path: str) -> None:
        r = self.client.delete(path)
        if r.status_code not in (200, 204, 404):
            r.raise_for_status()

    def test_connection(self) -> bool:
        """Hits a cheap, auth-required endpoint to confirm token validity."""
        try:
            self._get_json("/core/users/me/")
            return True
        except httpx.HTTPError:
            return False

    # ── search helpers (Authentik IGNORES the ?name=/?slug= URL filters and
    # returns the full list — every callsite MUST filter client-side or risk
    # PATCH-ing the wrong row) ───────────────────────────────────────────

    @staticmethod
    def _find_by_field(rows: list[dict], field: str, value) -> dict | None:
        for r in rows:
            if r.get(field) == value:
                return r
        return None

    @staticmethod
    def _find_by_name(rows: list[dict], name: str) -> dict | None:
        return AuthentikManager._find_by_field(rows, "name", name)

    def _applications(self) -> list[dict]:
        """All applications for management.

        ``/core/applications/`` filters to apps the CALLER is authorized to launch,
        so once an app is bound to groups the admin token isn't in (the access gate),
        it would DISAPPEAR from the default list and idempotent re-runs would fail to
        find it. ``superuser_full_list=true`` returns every app regardless of policy.
        """
        return self._get_json(
            "/core/applications/", superuser_full_list="true", page_size=1000
        ).get("results", [])

    # ── flow lookup (read-once cache) ───────────────────────────────────

    def _flow_pk(self, slug: str) -> str:
        if slug in self._flow_cache:
            return self._flow_cache[slug]
        results = self._get_json("/flows/instances/", slug=slug).get("results", [])
        if not results:
            raise RuntimeError(f"Authentik flow {slug!r} not found")
        self._flow_cache[slug] = results[0]["pk"]
        return self._flow_cache[slug]

    # ── Proxy / Forward-Auth (Phase C — Open WebUI) ─────────────────────

    def proxy_app_ensure(self, app: ProxyApp) -> ProxyAppResult:
        """Create or update a forward-auth Proxy Provider + Application.

        Idempotent: re-running with the same slug updates external_host in
        place. Returns the provider + application PKs (needed to attach to the
        outpost).
        """
        # Resolve the well-known authorization + invalidation flows.
        auth_flow_pk = self._flow_pk(DEFAULT_AUTHORIZATION_FLOW_SLUG)
        invalidation_flow_pk = self._flow_pk(DEFAULT_INVALIDATION_FLOW_SLUG)

        # Find or create the Proxy Provider.
        # NB: Authentik IGNORES the ?name= URL filter on /providers/proxy/ —
        # the server returns the full list regardless. We MUST filter
        # client-side; otherwise we'd PATCH whichever row is first in the
        # list and silently mangle unrelated providers (issue #45 PoC bug).
        provider_rows = self._get_json("/providers/proxy/").get("results", [])
        existing_provider = self._find_by_name(provider_rows, app.name)
        provider_body = {
            "name": app.name,
            "authorization_flow": auth_flow_pk,
            "invalidation_flow": invalidation_flow_pk,
            "external_host": app.external_host,
            "mode": "forward_single",
        }
        if existing_provider:
            provider_pk = existing_provider["pk"]
            self._patch_json(f"/providers/proxy/{provider_pk}/", provider_body)
        else:
            provider_pk = self._post_json("/providers/proxy/", provider_body)["pk"]

        # Find or create the Application — slug is the immutable key.
        # Same client-side filter (Authentik ignores ?slug= too). Also: an
        # Application has a 1:1 link to a Provider; if some OTHER app already
        # owns this provider_pk, reuse THAT app rather than POSTing a new one
        # (Authentik would 400 "Application with this provider already exists").
        app_rows = self._applications()
        existing_app = (
            self._find_by_field(app_rows, "slug", app.slug)
            or self._find_by_field(app_rows, "provider", provider_pk)
        )
        app_body = {
            "name": app.name,
            "slug": app.slug,
            "provider": provider_pk,
            "meta_description": app.description,
            "meta_launch_url": app.launch_url or app.external_host,
        }
        if existing_app:
            application_pk = existing_app["pk"]
            # Authentik's /core/applications/<x>/ detail endpoint routes on
            # SLUG, not pk (lookup_field="slug" on the viewset). PATCH-by-pk
            # returns 404; PATCH-by-slug works.
            self._patch_json(f"/core/applications/{existing_app['slug']}/", app_body)
        else:
            application_pk = self._post_json("/core/applications/", app_body)["pk"]

        return ProxyAppResult(
            application_pk=application_pk,
            provider_pk=provider_pk,
            slug=app.slug,
        )

    def app_delete(self, slug: str) -> None:
        """Remove an Application and its Provider (proxy or oidc) by slug. Idempotent."""
        # Client-side filter — Authentik's ?slug= URL filter is ignored.
        all_apps = self._applications()
        match = self._find_by_field(all_apps, "slug", slug)
        apps = [match] if match else []
        for a in apps:
            provider_pk = a.get("provider")
            # Authentik routes /core/applications/<x>/ on SLUG, not pk.
            self._delete(f"/core/applications/{a['slug']}/")
            if provider_pk:
                # Delete the backing provider. Provider pks are unique across
                # provider types, so attempt BOTH endpoints — the matching one
                # deletes, the other 404s harmlessly (_delete tolerates 404).
                # Do NOT break after the first: a 404 is not a successful delete,
                # so breaking on the proxy attempt would leak an oauth2 provider
                # (the OIDC case — caught by identity/test.sh --deep §7 teardown).
                for endpoint in ("/providers/proxy", "/providers/oauth2"):
                    self._delete(f"{endpoint}/{provider_pk}/")

    def app_provider_pk(self, slug: str) -> int | None:
        """The provider pk of the Application with this slug; None when absent."""
        app = self._find_by_field(self._applications(), "slug", slug)
        return app.get("provider") if app else None

    def app_is_proxy(self, slug: str) -> bool:
        """True when the Application with this slug is backed by a Proxy Provider."""
        provider_pk = self.app_provider_pk(slug)
        if not provider_pk:
            return False
        rows = self._get_json("/providers/proxy/", page_size=1000).get("results", [])
        return self._find_by_field(rows, "pk", provider_pk) is not None

    # ── Embedded Outpost ────────────────────────────────────────────────

    def _embedded_outpost(self) -> dict:
        # Client-side filter — Authentik's ?name= URL filter is ignored.
        all_outposts = self._get_json("/outposts/instances/").get("results", [])
        match = self._find_by_name(all_outposts, EMBEDDED_OUTPOST_NAME)
        if not match:
            raise RuntimeError(f"Authentik embedded outpost ({EMBEDDED_OUTPOST_NAME!r}) not found")
        return match

    def outpost_attach_provider(self, provider_pk: int) -> None:
        """Ensure the given provider PK is in the embedded outpost's providers list.

        Idempotent — patches in place if the provider isn't already attached.
        """
        outpost = self._embedded_outpost()
        providers = list(outpost.get("providers", []))
        if provider_pk in providers:
            return
        providers.append(provider_pk)
        self._patch_json(f"/outposts/instances/{outpost['pk']}/", {"providers": providers})

    def outpost_detach_provider(self, provider_pk: int) -> None:
        """Idempotent reverse of attach (used by accessControl/delete-service.sh)."""
        outpost = self._embedded_outpost()
        providers = [p for p in outpost.get("providers", []) if p != provider_pk]
        if len(providers) == len(outpost.get("providers", [])):
            return
        self._patch_json(f"/outposts/instances/{outpost['pk']}/", {"providers": providers})

    def outpost_set_authentik_host(self, authentik_host: str) -> None:
        """Set the embedded outpost's authentik_host (the identity public URL).

        Run once at identity install time (Phase B): tells the embedded outpost
        where to redirect users for the login UI. Without this, forward-auth
        flows redirect to the internal hostname which isn't reachable externally.
        """
        outpost = self._embedded_outpost()
        # `config` is a dict on Outpost; merge rather than replace so we keep
        # log_level / docker_network / kubernetes_replicas / etc.
        cfg = dict(outpost.get("config") or {})
        cfg["authentik_host"] = authentik_host
        self._patch_json(f"/outposts/instances/{outpost['pk']}/", {"config": cfg})

    @staticmethod
    def _drift_finding(field: str, expected, actual) -> dict:
        return {"field": field, "expected": expected, "actual": actual,
                "in_sync": actual == expected}

    def check_self_config(self, external_host: str, name: str = "identity") -> list[dict]:
        """Report drift of the identity self-config vs the expected public host.

        Reads the four domain-bearing objects (identity application launch URL,
        proxy provider external_host, oauth2 provider redirect_uris, embedded
        outpost authentik_host) and compares them to ``external_host``
        (``https://identity.<domain>``) WITHOUT mutating anything — the detector
        for a domain change that was not reconciled (#474). Returns one finding
        per object: ``{field, expected, actual, in_sync}``.
        """
        findings: list[dict] = []

        app = self._find_by_name(self._applications(), name)
        findings.append(self._drift_finding(
            "application.meta_launch_url", external_host,
            (app or {}).get("meta_launch_url"),
        ))

        proxy = self._find_by_name(
            self._get_json("/providers/proxy/").get("results", []), name)
        findings.append(self._drift_finding(
            "provider.proxy.external_host", external_host,
            (proxy or {}).get("external_host"),
        ))

        oauth = self._find_by_name(
            self._get_json("/providers/oauth2/", page_size=1000).get("results", []), name)
        uris = [u.get("url", "") for u in (oauth or {}).get("redirect_uris", [])]
        stale = [u for u in uris if not u.startswith(external_host)]
        findings.append({
            "field": "provider.oauth2.redirect_uris",
            "expected": f"all under {external_host}",
            "actual": uris,
            "in_sync": bool(uris) and not stale,
        })

        outpost = self._find_by_name(
            self._get_json("/outposts/instances/").get("results", []),
            EMBEDDED_OUTPOST_NAME)
        findings.append(self._drift_finding(
            "outpost.authentik_host", external_host,
            ((outpost or {}).get("config") or {}).get("authentik_host"),
        ))
        return findings

    # ── Groups / Roles (ADR-006) ────────────────────────────────────────

    def groups_list(self) -> list[dict]:
        """All groups (handles pagination defensively for small directories)."""
        return self._get_json("/core/groups/", page_size=1000).get("results", [])

    def group_get(self, name: str) -> dict | None:
        # Authentik ignores ?name=; filter client-side (see search-helpers note).
        return self._find_by_name(self.groups_list(), name)

    def group_ensure(
        self,
        name: str,
        *,
        parent_name: str | None = None,
        is_superuser: bool = False,
        attributes: dict | None = None,
    ) -> dict:
        """Create or update a group by name (idempotent).

        ``parent_name`` must already exist — the caller creates parent groups
        before their children. Returns the full group dict (incl. ``pk``).
        """
        parent_pk = None
        if parent_name:
            parent = self.group_get(parent_name)
            if not parent:
                raise RuntimeError(
                    f"parent group {parent_name!r} not found — create it before {name!r}"
                )
            parent_pk = parent["pk"]

        body: dict = {"name": name, "is_superuser": is_superuser}
        # 2025.12 made a group's parent a list (``parents``, many-to-many); the
        # single ``parent`` is gone. Before it, ``parent`` is the field.
        if self._at_least("2025.12"):
            body["parents"] = [parent_pk] if parent_pk else []
        else:
            body["parent"] = parent_pk
        if attributes is not None:
            body["attributes"] = attributes

        existing = self.group_get(name)
        if existing:
            # Don't clobber attributes the operator may have added by hand: merge.
            if attributes is not None:
                merged = dict(existing.get("attributes") or {})
                merged.update(attributes)
                body["attributes"] = merged
            return self._patch_json(f"/core/groups/{existing['pk']}/", body)
        return self._post_json("/core/groups/", body)

    # ── Users (ADR-006) ─────────────────────────────────────────────────

    def users_list(self) -> list[dict]:
        return self._get_json("/core/users/", page_size=1000).get("results", [])

    def user_get(self, username: str) -> dict | None:
        return self._find_by_field(self.users_list(), "username", username)

    def _group_pks(self, names: list[str]) -> list[str]:
        """Resolve group names → pks; raise on any missing (caller ensures first)."""
        by_name = {g["name"]: g["pk"] for g in self.groups_list()}
        missing = [n for n in names if n not in by_name]
        if missing:
            raise RuntimeError(f"groups not found (create them first): {missing}")
        return [by_name[n] for n in names]

    def user_ensure(
        self,
        username: str,
        *,
        email: str = "",
        name: str | None = None,
        group_names: list[str] | None = None,
        attributes: dict | None = None,
        is_active: bool = True,
        path: str = "users",
    ) -> dict:
        """Create or update a user by username (idempotent).

        Group membership is *additive* — existing memberships are preserved and
        the requested groups merged in (never removes the user from other groups).
        """
        group_pks = self._group_pks(group_names or [])
        existing = self.user_get(username)
        body: dict = {
            "username": username,
            "name": name if name is not None else (existing.get("name") if existing else username),
            "email": email,
            "type": "internal",
            "is_active": is_active,
            "path": path,
        }
        if attributes is not None:
            body["attributes"] = attributes

        if existing:
            merged = sorted(set(existing.get("groups", [])) | set(group_pks))
            body["groups"] = merged
            return self._patch_json(f"/core/users/{existing['pk']}/", body)
        body["groups"] = group_pks
        return self._post_json("/core/users/", body)

    def user_add_to_groups(self, username: str, group_names: list[str]) -> dict:
        """Add an existing user to the named groups (additive, idempotent)."""
        user = self.user_get(username)
        if not user:
            raise RuntimeError(f"user {username!r} not found")
        want = set(self._group_pks(group_names))
        have = set(user.get("groups", []))
        if want <= have:
            return user
        return self._patch_json(
            f"/core/users/{user['pk']}/", {"groups": sorted(have | want)}
        )

    def user_remove_from_groups(self, username: str, group_names: list[str]) -> dict:
        """Remove an existing user from the named groups (idempotent)."""
        user = self.user_get(username)
        if not user:
            raise RuntimeError(f"user {username!r} not found")
        drop = set(self._group_pks(group_names))
        have = set(user.get("groups", []))
        keep = sorted(have - drop)
        if len(keep) == len(have):
            return user
        return self._patch_json(f"/core/users/{user['pk']}/", {"groups": keep})

    def group_delete(self, name: str) -> bool:
        """Delete a group (ordinary group OR role-group) by name.

        Returns False if it didn't exist. Authentik cascades the membership
        rows, so callers need not unlink members first.
        """
        group = self.group_get(name)
        if not group:
            return False
        self._delete(f"/core/groups/{group['pk']}/")
        return True

    def user_delete(self, username: str) -> bool:
        """Delete a user entirely. Returns False if the user didn't exist."""
        user = self.user_get(username)
        if not user:
            return False
        self._delete(f"/core/users/{user['pk']}/")
        return True

    def user_set_password(self, username: str, password: str) -> None:
        """Set a user's password directly (fallback when no recovery flow/SMTP)."""
        user = self.user_get(username)
        if not user:
            raise RuntimeError(f"user {username!r} not found")
        r = self.client.post(f"/core/users/{user['pk']}/set_password/", json={"password": password})
        if r.status_code not in (200, 204):
            r.raise_for_status()

    def user_recovery_link(self, username: str) -> str | None:
        """Return a one-time recovery/enrollment link, or None if no recovery flow
        is configured on the brand (then the caller falls back to set_password).
        """
        user = self.user_get(username)
        if not user:
            raise RuntimeError(f"user {username!r} not found")
        r = self.client.post(f"/core/users/{user['pk']}/recovery/")
        if r.status_code in (400, 404):
            return None          # brand has no flow_recovery set → caller falls back
        r.raise_for_status()
        return r.json().get("link")

    # ── Password recovery: admin-issued link, no SMTP (option B) ────────
    #
    # ``/core/users/<pk>/recovery/`` only returns a link when the BRAND has
    # ``flow_recovery`` set, and Authentik ships no recovery flow at all — its
    # stock one is an unapplied example blueprint that fronts the password
    # prompt with an e-mail verification stage, i.e. dead weight until SMTP
    # exists. So TAPPaaS owns a minimal one: prompt for a new password, write
    # it. The ``flow_token`` in the link IS the authentication (it carries the
    # pending user), which is why no identification or e-mail stage is needed.
    #
    # Every object below is keyed by NAME and reconciled in place, so
    # identity/update.sh can re-run this on every install and update. Owning
    # our own stage objects (rather than reusing Authentik's stock
    # ``default-password-change-*`` ones) keeps password recovery working even
    # if an operator edits the built-in password-change flow.

    def _prompt_ensure(self, name: str, *, field_key: str, label: str, order: int) -> str:
        """Create/update one password Prompt field by name. Returns its pk."""
        rows = self._get_json("/stages/prompt/prompts/", page_size=1000).get("results", [])
        existing = self._find_by_name(rows, name)
        body = {
            "name": name,
            "field_key": field_key,
            "label": label,
            "type": "password",
            "required": True,
            "placeholder": label,
            "order": order,
        }
        if existing:
            # Reconcile in place; the pk is the one we already looked up.
            self._patch_json(f"/stages/prompt/prompts/{existing['pk']}/", body)
            return existing["pk"]
        return self._post_json("/stages/prompt/prompts/", body)["pk"]

    def _prompt_stage_ensure(self, name: str, field_pks: list[str]) -> str:
        """Create/update a Prompt stage holding exactly ``field_pks``.

        Two password-type fields make Authentik enforce the "passwords match"
        check itself — that is why the repeat field is not cosmetic.
        """
        rows = self._get_json("/stages/prompt/stages/", page_size=1000).get("results", [])
        existing = self._find_by_name(rows, name)
        body = {"name": name, "fields": field_pks}
        if existing:
            # Reconcile in place; the pk is the one we already looked up.
            self._patch_json(f"/stages/prompt/stages/{existing['pk']}/", body)
            return existing["pk"]
        return self._post_json("/stages/prompt/stages/", body)["pk"]

    def _user_write_stage_ensure(self, name: str) -> str:
        """Create/update the user_write stage that commits the new password.

        ``never_create``: this stage can only write to the user the flow_token
        restored. Someone opening the flow URL without a token gets an invalid
        stage, never a newly created account.
        """
        rows = self._get_json("/stages/user_write/", page_size=1000).get("results", [])
        existing = self._find_by_name(rows, name)
        body = {"name": name, "user_creation_mode": "never_create"}
        if existing:
            # Reconcile in place; the pk is the one we already looked up.
            self._patch_json(f"/stages/user_write/{existing['pk']}/", body)
            return existing["pk"]
        return self._post_json("/stages/user_write/", body)["pk"]

    def _flow_binding_ensure(self, flow_pk: str, stage_pk: str, order: int) -> bool:
        """Bind a stage into a flow at ``order`` (idempotent). True if created.

        Authentik ignores ?target= here as elsewhere, so the (target, stage)
        pair is matched client-side; a binding that exists at the wrong order
        is moved rather than duplicated.
        """
        rows = self._get_json("/flows/bindings/", page_size=1000).get("results", [])
        for b in rows:
            if b.get("target") == flow_pk and b.get("stage") == stage_pk:
                if b.get("order") != order:
                    self._patch_json(f"/flows/bindings/{b['pk']}/", {"order": order})
                return False
        self._post_json("/flows/bindings/", {
            "target": flow_pk,
            "stage": stage_pk,
            "order": order,
            # Mirrors Authentik's own default-password-change bindings.
            "evaluate_on_plan": False,
            "re_evaluate_policies": True,
        })
        return True

    def brand_default(self) -> dict:
        """The brand every request falls back to (the one with ``default``).

        A stock install has exactly one, domain ``authentik-default``.
        """
        rows = self._get_json("/core/brands/", page_size=1000).get("results", [])
        brand = next((b for b in rows if b.get("default")), None)
        if not brand:
            raise RuntimeError("no default brand in Authentik (expected one with default=true)")
        return brand

    # ── site branding (#479) ─────────────────────────────────────────────
    # The login page shows the site, not Authentik: a logo with the site's name
    # and "powered by TAPPaaS", the site's name as the page title, a neutral
    # flow heading. Files are uploaded under a content-hashed name, so a changed
    # name is a new file and an unchanged one is not uploaded again.

    def file_names(self, usage: str = "media") -> set[str]:
        r = self.client.get("/admin/file/", params={"usage": usage})
        r.raise_for_status()
        return {f.get("name", "") for f in r.json() if isinstance(f, dict)}

    def file_upload(self, name: str, content: bytes, mime: str, usage: str = "media") -> None:
        r = self.client.post("/admin/file/", files={"file": (name, content, mime)},
                             data={"name": name, "usage": usage})
        r.raise_for_status()

    def brand_ensure(self, site_name: str, flow_title: str = "Sign in",
                     logo: tuple[bytes, str] | None = None,
                     logo_dark: tuple[bytes, str] | None = None) -> list[str]:
        """Brand the default brand and its login flow for ``site_name``.

        ``logo``/``logo_dark`` are the site's own logo as (content, extension);
        without them the logo is generated from the name. One file serves both
        themes; with ``logo_dark`` too, Authentik picks by the viewer's theme.
        Returns what changed (empty: already so).
        """
        changed: list[str] = []
        brand = self.brand_default()
        if logo is None:
            variants = {t: (site_logo_svg(site_name, t).encode(), "svg") for t in LOGO_COLOURS}
        elif logo_dark is None:
            variants = {"": logo}
        else:
            if logo[1] != logo_dark[1]:
                raise ValueError("the light and dark logos must be the same file type "
                                 f"(got .{logo[1]} and .{logo_dark[1]})")
            variants = {"light": logo, "dark": logo_dark}
        ext = next(iter(variants.values()))[1]
        tag = hashlib.sha256(b"".join(variants[t][0] for t in sorted(variants))).hexdigest()[:12]
        # Authentik substitutes the viewer's theme for %(theme)s.
        logo_name = (f"tappaas-site-logo-{tag}-%(theme)s.{ext}" if "" not in variants
                     else f"tappaas-site-logo-{tag}.{ext}")
        icon = site_icon_svg(site_name).encode()
        icon_name = f"tappaas-site-icon-{hashlib.sha256(icon).hexdigest()[:12]}.svg"
        have = self.file_names()
        uploads = [(logo_name.replace("%(theme)s", t), variants[t][0], LOGO_MIME[ext]) for t in sorted(variants)]
        uploads.append((icon_name, icon, "image/svg+xml"))
        for name, data, mime in uploads:
            if name not in have:
                self.file_upload(name, data, mime)
                changed.append(f"uploaded {name}")
        want = {"branding_title": site_name, "branding_logo": logo_name, "branding_favicon": icon_name}
        delta = {k: v for k, v in want.items() if brand.get(k) != v}
        if delta:
            self._patch_json(f"/core/brands/{brand['brand_uuid']}/", delta)
            changed.extend(f"brand {k} → {v}" for k, v in delta.items())
        flow_pk = brand.get("flow_authentication")
        if flow_pk:
            rows = self._get_json("/flows/instances/", page_size=1000).get("results", [])
            flow = self._find_by_field(rows, "pk", flow_pk)
            if flow and flow.get("title") != flow_title:
                self._patch_json(f"/flows/instances/{flow['slug']}/", {"title": flow_title})
                changed.append(f"flow '{flow['slug']}' title → {flow_title}")
        return changed

    def brand_set_recovery_flow(self, flow_pk: str) -> tuple[bool, str]:
        """Point the default brand's flow_recovery at ``flow_pk``.

        Returns (changed, brand_domain).
        """
        brand = self.brand_default()
        if brand.get("flow_recovery") == flow_pk:
            return False, brand.get("domain", "")
        self._patch_json(f"/core/brands/{brand['brand_uuid']}/", {"flow_recovery": flow_pk})
        return True, brand.get("domain", "")

    def recovery_flow_ensure(
        self,
        *,
        slug: str = RECOVERY_FLOW_SLUG,
        title: str = RECOVERY_FLOW_TITLE,
        authentication: str = "none",
        attach_to_brand: bool = True,
    ) -> dict:
        """Create/reconcile the recovery flow and point the brand at it.

        ``authentication`` is the flow's entry requirement:

          ``none``                    — the default. The flow_token is the gate,
                                        so a user with a live Authentik session
                                        can still use the link (Authentik's own
                                        password-change flow likewise re-writes
                                        a password without asking for the old
                                        one, so this adds no new exposure).
          ``require_unauthenticated`` — upstream's stricter setting: the link
                                        then only works in a logged-out browser.

        Returns a dict describing what the reconcile did.
        """
        rows = self._get_json("/flows/instances/", page_size=1000).get("results", [])
        existing = self._find_by_field(rows, "slug", slug)
        body = {
            "name": RECOVERY_FLOW_NAME,
            "slug": slug,
            "title": title,
            "designation": "recovery",
            "authentication": authentication,
            "denied_action": "message_continue",
            "layout": "stacked",
            "policy_engine_mode": "any",
            "compatibility_mode": False,
        }
        if existing:
            flow_pk = existing["pk"]
            self._patch_json(f"/flows/instances/{slug}/", body)
            created = False
        else:
            flow_pk = self._post_json("/flows/instances/", body)["pk"]
            created = True
        self._flow_cache[slug] = flow_pk

        password_pk = self._prompt_ensure(
            RECOVERY_PROMPT_PASSWORD, field_key="password", label="New password", order=300,
        )
        repeat_pk = self._prompt_ensure(
            RECOVERY_PROMPT_PASSWORD_REPEAT, field_key="password_repeat",
            label="New password (repeat)", order=301,
        )
        prompt_stage_pk = self._prompt_stage_ensure(
            RECOVERY_PROMPT_STAGE_NAME, [password_pk, repeat_pk],
        )
        write_stage_pk = self._user_write_stage_ensure(RECOVERY_WRITE_STAGE_NAME)

        bindings_created = 0
        bindings_created += self._flow_binding_ensure(flow_pk, prompt_stage_pk, 10)
        bindings_created += self._flow_binding_ensure(flow_pk, write_stage_pk, 20)

        brand_changed, brand_domain = False, ""
        if attach_to_brand:
            brand_changed, brand_domain = self.brand_set_recovery_flow(flow_pk)

        return {
            "slug": slug,
            "flow_pk": flow_pk,
            "created": created,
            "bindings_created": bindings_created,
            "attached_to_brand": attach_to_brand,
            "brand_changed": brand_changed,
            "brand_domain": brand_domain,
        }

    # ── Access bindings: group → Application (ADR-006 §5) ────────────────

    def app_bind_groups(self, slug: str, group_names: list[str]) -> int:
        """Bind the named groups to an Application via PolicyBindings (additive).

        This is the access gate: without any binding, Authentik allows ALL users
        into the app (fail-open). Returns the count of bindings newly created.
        Idempotent — skips groups already bound.
        """
        all_apps = self._applications()
        app = self._find_by_field(all_apps, "slug", slug)
        if not app:
            raise RuntimeError(f"application {slug!r} not found")
        target = app["pk"]
        group_pks = self._group_pks(group_names)

        # Authentik ignores ?target=; pull all bindings and filter client-side.
        bindings = self._get_json("/policies/bindings/", page_size=1000).get("results", [])
        bound = {b.get("group") for b in bindings if b.get("target") == target}
        existing_orders = [b.get("order", 0) for b in bindings if b.get("target") == target]
        next_order = (max(existing_orders) + 1) if existing_orders else 0

        created = 0
        for gpk in group_pks:
            if gpk in bound:
                continue
            self._post_json("/policies/bindings/", {
                "target": target,
                "group": gpk,
                "order": next_order,
                "enabled": True,
                "negate": False,
                "timeout": 30,
            })
            next_order += 1
            created += 1
        return created

    # ── OIDC (ADR-006 — Nextcloud & other native-OIDC apps) ─────────────

    def _scope_mapping_pks(self, names: list[str]) -> list[str]:
        """Resolve OIDC scope-mapping names → pks; skip unknown with a note."""
        rows = self._get_json("/propertymappings/provider/scope/", page_size=1000).get("results", [])
        # A mapping's own name first: several mappings can share a scope_name
        # (two emit "groups"), and which one a scope_name picks is arbitrary.
        by_mapping = {r["name"]: r["pk"] for r in rows if r.get("name")}
        by_scope = {r["scope_name"]: r["pk"] for r in rows}
        pks, missing = [], []
        for n in names:
            pk = by_mapping.get(n) or by_scope.get(n)
            (pks.append(pk) if pk else missing.append(n))
        if missing:
            # Non-fatal: the app simply won't receive claims for these scopes.
            print(f"    warning: OIDC scope mapping(s) not found, skipping: {missing}")
        return pks

    def scope_mapping_ensure(self, name: str, scope_name: str, expression: str,
                             description: str = "") -> dict:
        """Create or update an OIDC scope mapping by name (idempotent)."""
        rows = self._get_json("/propertymappings/provider/scope/", page_size=1000).get("results", [])
        body = {"name": name, "scope_name": scope_name, "expression": expression,
                "description": description}
        existing = self._find_by_name(rows, name)
        if existing:
            return self._patch_json(f"/propertymappings/provider/scope/{existing['pk']}/", body)
        return self._post_json("/propertymappings/provider/scope/", body)

    def email_mapping_ensure(self) -> str:
        """The TAPPaaS ``email`` scope mapping (verified); returns its pk, "" if
        Authentik did not return one."""
        m = self.scope_mapping_ensure(
            EMAIL_VERIFIED_MAPPING, "email", EMAIL_VERIFIED_EXPRESSION,
            "TAPPaaS: operator-set addresses are verified (#748, Authentik 2025.10)")
        return str(m.get("pk") or "")

    def _email_scope_pks(self) -> set[str]:
        """Every scope mapping that answers the ``email`` scope."""
        rows = self._get_json("/propertymappings/provider/scope/", page_size=1000).get("results", [])
        return {r["pk"] for r in rows if r.get("scope_name") == "email"}

    def oidc_email_verified_ensure(self) -> int:
        """Put the TAPPaaS ``email`` mapping on every OAuth2 provider in place of
        any other ``email`` mapping. Idempotent; returns how many changed."""
        ours = self.email_mapping_ensure()
        if not ours:
            raise RuntimeError(f"could not create the {EMAIL_VERIFIED_MAPPING!r} scope mapping")
        others = self._email_scope_pks() - {ours}
        changed = 0
        for p in self._get_json("/providers/oauth2/", page_size=1000).get("results", []):
            have = list(p.get("property_mappings") or [])
            if not any(pk in others or pk == ours for pk in have):
                continue          # a provider with no email scope gets none
            want = [pk for pk in have if pk not in others]
            if ours not in want:
                want.append(ours)
            if want != have:
                self._patch_json(f"/providers/oauth2/{p['pk']}/", {"property_mappings": want})
                changed += 1
        return changed

    def _default_signing_key_pk(self) -> str:
        """A certificate-key pair to sign ID tokens (Nextcloud validates via JWKS)."""
        rows = self._get_json("/crypto/certificatekeypairs/", has_key=True, page_size=100).get("results", [])
        if not rows:
            raise RuntimeError("no signing certificate-key pair available for OIDC")
        preferred = self._find_by_name(rows, "authentik Self-signed Certificate")
        return (preferred or rows[0])["pk"]

    def oidc_app_ensure(self, app: OidcApp) -> OidcAppResult:
        """Create or update an OIDC (OAuth2/OpenID) Provider + Application.

        Idempotent on slug/name; the client_secret is generated once by Authentik
        and preserved across re-runs. Returns the client_id/secret for the app's
        own OIDC client config (e.g. Nextcloud user_oidc).
        """
        auth_flow_pk = self._flow_pk(DEFAULT_AUTHORIZATION_FLOW_SLUG)
        invalidation_flow_pk = self._flow_pk(DEFAULT_INVALIDATION_FLOW_SLUG)
        scopes = list(app.scopes or DEFAULT_OIDC_SCOPES)
        # The TAPPaaS email mapping in place of the stock one — or, if it cannot
        # be made, the stock one: an app without an email claim is worse.
        if "email" in scopes and self.email_mapping_ensure():
            scopes = [EMAIL_VERIFIED_MAPPING if s == "email" else s for s in scopes]
        scope_pks = self._scope_mapping_pks(scopes)
        signing_key = self._default_signing_key_pk()
        redirect_uris = [{"matching_mode": "strict", "url": u} for u in app.redirect_uris]

        provider_body = {
            "name": app.name,
            "authorization_flow": auth_flow_pk,
            "invalidation_flow": invalidation_flow_pk,
            "client_type": "confidential",
            "redirect_uris": redirect_uris,
            "property_mappings": scope_pks,
            "signing_key": signing_key,
            "sub_mode": "hashed_user_id",
        }

        provider_rows = self._get_json("/providers/oauth2/", page_size=1000).get("results", [])
        existing_provider = self._find_by_name(provider_rows, app.name)
        if existing_provider:
            provider_pk = existing_provider["pk"]
            # Add the login grants, never narrow: a provider an upgrade gave every
            # grant (or an operator widened) keeps the rest.
            grants = list(existing_provider.get("grant_types") or [])
            grants += [g for g in OIDC_LOGIN_GRANT_TYPES if g not in grants]
            provider = self._patch_json(f"/providers/oauth2/{provider_pk}/",
                                        {**provider_body, "grant_types": grants})
        else:
            provider = self._post_json("/providers/oauth2/",
                                       {**provider_body, "grant_types": list(OIDC_LOGIN_GRANT_TYPES)})
            provider_pk = provider["pk"]

        # Find or create the Application (slug is the immutable key; reuse an app
        # that already owns this provider to avoid the 1:1 "already exists" 400).
        app_rows = self._applications()
        existing_app = (
            self._find_by_field(app_rows, "slug", app.slug)
            or self._find_by_field(app_rows, "provider", provider_pk)
        )
        app_body = {
            "name": app.name,
            "slug": app.slug,
            "provider": provider_pk,
            "meta_description": app.description,
        }
        if app.launch_url:
            app_body["meta_launch_url"] = app.launch_url
        if existing_app:
            application_pk = existing_app["pk"]
            self._patch_json(f"/core/applications/{existing_app['slug']}/", app_body)
        else:
            application_pk = self._post_json("/core/applications/", app_body)["pk"]

        return OidcAppResult(
            application_pk=application_pk,
            provider_pk=provider_pk,
            slug=app.slug,
            client_id=provider["client_id"],
            client_secret=provider["client_secret"],
        )
