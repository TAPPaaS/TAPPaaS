"""Render a per-node Proxmox VE ``answer.toml`` (design N3/N4).

Field set per the PVE >= 8.2 automated-installation docs
(https://pve.proxmox.com/wiki/Automated_Installation): ``[global]`` with
keyboard/country/fqdn/mailto/timezone/root-password/root-ssh-keys,
``[network]`` from-dhcp, ``[disk-setup]`` on the boot disk.

TAPPaaS disk standard (ADR-037 D1): the PVE system lives on the boot disk,
ZFS by default (``rpool``; its ``rpool/data`` is the storage ``local-zfs``,
which carries the guests on a node with no data disk), ext4/LVM on request.
The tankXY data pools are separate whole-disk ZFS pools created POST-JOIN by
the storage plane (config-storage.sh / site.json) — the installer must never
touch them.

TODO(V-2): validate the exact schema against the deployed PVE version's
``proxmox-auto-install-assistant validate-answer`` on a PVE node — key
casing (kebab-case per docs) and the accepted zfs.raid values must be
confirmed on hardware before first use.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from .log import warn
from .registry import is_kernel_disk_name

DEFAULT_KEYBOARD = "en-us"
DEFAULT_COUNTRY = "us"
DEFAULT_TIMEZONE = "UTC"

# NOTE: declared pools are post-join data pools (TAPPaaS standard, cf.
# tappaas1) — the installer only ever formats the boot disk.


def _toml_str(value: str) -> str:
    """Encode a python string as a TOML basic string.

    JSON string escaping is a valid subset of TOML basic-string escaping.
    """
    return json.dumps(str(value))


def _toml_str_list(values) -> str:
    return "[" + ", ".join(_toml_str(v) for v in values) + "]"


def load_site(site_path) -> dict:
    """Best-effort read of site.json ({} when missing/unreadable)."""
    try:
        return json.loads(Path(site_path).read_text())
    except (OSError, json.JSONDecodeError) as e:
        warn(f"cannot read site.json at {site_path}: {e} — using defaults")
        return {}


def render_answer(
    name: str,
    domain: str,
    root_password: str,
    ssh_keys,
    pools,
    boot_disk: str = "sda",
    boot_filesystem: str = "zfs",
    boot_mirror: str = "",
    country: str = DEFAULT_COUNTRY,
    tz: str = DEFAULT_TIMEZONE,
    mailto: str = "",
    keyboard: str = DEFAULT_KEYBOARD,
    mgmt_mac: str = "",
    mgmt_cidr: str = "",
    mgmt_gateway: str = "",
) -> str:
    """Render answer.toml for a registered node.

    Args:
        name: Node name (hostname part).
        domain: DNS domain for the FQDN (mgmt plane, e.g. mgmt.internal).
        root_password: Generated plaintext root password (stored 0600 by
            the caller; day-2 access is SSH-keys-only per design §4).
        ssh_keys: Public keys placed in root's authorized_keys by the
            installer.
        pools: Registration pool dicts ({name, layout, disks}) — post-join
            data pools, listed as a comment only (never installed to).
        boot_disk: The disk the PVE system is installed on.
        boot_filesystem: zfs (default, a single-disk ``rpool``, raid0) or
            ext4 (LVM).
        boot_mirror: a second disk (kernel name): ``rpool`` becomes a zfs
            raid1 over both, and each disk gets its own EFI system partition.
        country / tz / mailto / keyboard: site-level installer settings.
        mgmt_mac / mgmt_cidr / mgmt_gateway: when all are given (a registration
            that pins its MACs), the management network is set from the answer
            on the NIC with that MAC — with DHCP the installer keeps whichever
            NIC got a lease first, which on a node with a second, WAN-side NIC
            can be the wrong one. Otherwise from DHCP.
    """
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    fqdn = f"{name}.{domain}"
    mailto = mailto or f"root@{domain}"

    lines = [
        f"# answer.toml for {fqdn} — generated by TAPPaaS node-provisioner {now}",
        "# One-shot: the matching registration is consumed after this answer.",
        "# TODO(V-2): schema validated against PVE docs only — run",
        "#   proxmox-auto-install-assistant validate-answer <this file>",
        "# on a PVE node to confirm for the deployed version.",
        "",
        "[global]",
        f"keyboard = {_toml_str(keyboard)}",
        f"country = {_toml_str(country.lower())}",
        f"fqdn = {_toml_str(fqdn)}",
        f"mailto = {_toml_str(mailto)}",
        f"timezone = {_toml_str(tz)}",
        f"root-password = {_toml_str(root_password)}",
        f"root-ssh-keys = {_toml_str_list(ssh_keys)}",
        "",
        "[network]",
    ]
    if mgmt_mac and mgmt_cidr and mgmt_gateway:
        lines += [
            "# the registered management NIC, by MAC, at the node's standard address",
            'source = "from-answer"',
            f"cidr = {_toml_str(mgmt_cidr)}",
            f"gateway = {_toml_str(mgmt_gateway)}",
            f"dns = {_toml_str(mgmt_gateway)}",
            f"filter.ID_NET_NAME_MAC = {_toml_str('*' + mgmt_mac.replace(':', '').lower())}",
        ]
    else:
        lines.append('source = "from-dhcp"')
    lines += [
        "",
        "[disk-setup]",
    ]
    if boot_filesystem == "ext4":
        lines += [
            "# ext4/LVM on the boot disk (pve-root): for a node with data disks",
            'filesystem = "ext4"',
        ]
    else:
        lines += [
            "# TAPPaaS standard (ADR-037 D1): ZFS on the boot disk — rpool; its",
            "# rpool/data (local-zfs) carries the guests when there is no data disk",
            'filesystem = "zfs"',
            'zfs.raid = "raid1"' if boot_mirror else 'zfs.raid = "raid0"',
        ]
    # The disk the installer WIPES. By serial whenever we have one: a udev filter
    # on ID_SERIAL picks that physical disk whatever the kernel calls it on this
    # boot. A kernel name (legacy) is only as good as the enumeration order.
    if boot_mirror:
        lines += [
            "# a mirrored boot pair, by kernel name: a serial filter selects one disk only,",
            "# and both disks are mirrored whichever the kernel numbers first",
            f"disk-list = {_toml_str_list([boot_disk, boot_mirror])}",
        ]
    elif is_kernel_disk_name(boot_disk):
        lines.append(f"disk-list = {_toml_str_list([boot_disk])}")
    else:
        lines += [
            "# the boot disk by SERIAL — stable across boots (kernel names are not)",
            f"filter.ID_SERIAL = {_toml_str('*' + boot_disk + '*')}",
        ]

    if pools:
        extra = ", ".join(
            "%s=%s:%s" % (p.get("name", "?"), p.get("layout", "?"),
                          "+".join(p.get("disks", [])))
            for p in pools)
        lines += [
            f"# NOTE: declared data pools ({extra}) are NOT created by the "
            "installer;",
            "# they are created post-join by the storage plane "
            "(config-storage.sh / site.json).",
        ]

    return "\n".join(lines) + "\n"


def answer_settings_from_site(site: dict) -> dict:
    """Extract installer settings (country/keyboard/timezone/mailto) from site.json.

    The keyboard comes from the site too (#408). It did not before, so every node
    installed this way came up with DEFAULT_KEYBOARD while the first node — where
    the operator actually answered the question — had their layout. A site.json
    that predates the keyboard still falls back to the default.

    The country and timezone are the primary location's, the keyboard is
    site-wide (ADR-036 D1); a site.json migration 0019 has not reached keeps
    all three under the retired `location`.
    """
    legacy = site.get("location") if isinstance(site.get("location"), dict) else {}
    locations = site.get("locations") if isinstance(site.get("locations"), dict) else {}
    location = locations.get(site.get("primaryLocation") or "") or legacy
    return {
        "country": (location.get("country") or DEFAULT_COUNTRY),
        "keyboard": (site.get("keyboard") or legacy.get("keyboard") or DEFAULT_KEYBOARD),
        "tz": (location.get("timezone") or DEFAULT_TIMEZONE),
        "mailto": (site.get("email") or ""),
    }
