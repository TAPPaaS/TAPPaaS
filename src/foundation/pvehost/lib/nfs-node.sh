#!/usr/bin/env bash
# nfs-node.sh — what a PVE node does to serve NFS shares (ADR-029 v0.9 D4, D4a, D16,
# D19): build and share, on this node, every share config/shares.json declares for
# it. Behind the node's NFS server hook (../storage/nfs-server.sh); never decides
# WHAT to serve — shares.json does — only how, on a PVE node. The share alias and
# telling consumers are storage-manager's (storage/lib/nfs-converge.sh).
#
# Runs on the mothership, acting on the node as root through pn_ssh. Sourced after
# common-install-routines.sh, pvehost-lib.sh and the storage module's nfs-lib.sh;
# INSTANCE and ADDRESS must be set. Idempotent throughout.

# nfs_node_ensure_server — nfs-kernel-server, NFSv4 only (ADR-029 D4). Installed on
# a node's FIRST export, never before: a node with no export runs no NFS server.
nfs_node_ensure_server() {
    if ! pn_ssh 'dpkg-query -W -f="\${Status}" nfs-kernel-server 2>/dev/null | grep -q "install ok installed"'; then
        info "  installing nfs-kernel-server on ${INSTANCE}"
        pn_ssh 'DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nfs-kernel-server >/dev/null' \
            || { error "  could not install nfs-kernel-server on ${INSTANCE}"; return 1; }
    fi
    # v4 only: one port (tcp/2049) for the firewall rule to open, no mountd/statd
    # surface. rpcbind itself is left alone — Proxmox's own NFS storage client
    # uses it — and the per-pair rule never opens 111.
    local conf='# GENERATED by the storage module through the pvehost NFS hook (ADR-029 D19). Do not edit here.
[nfsd]
vers3=n
'
    if [[ "$(pn_ssh 'cat /etc/nfs.conf.d/tappaas.conf 2>/dev/null')" != "${conf%$'\n'}" ]]; then
        printf '%s' "${conf}" | pn_ssh_stdin 'mkdir -p /etc/nfs.conf.d && cat > /etc/nfs.conf.d/tappaas.conf' \
            || { error "  could not write /etc/nfs.conf.d/tappaas.conf on ${INSTANCE}"; return 1; }
        pn_ssh 'systemctl restart nfs-server' || { error "  nfs-server did not restart on ${INSTANCE}"; return 1; }
        info "  ${GN}✓${CL} nfs-server on ${INSTANCE}: NFSv4 only"
    fi
    pn_ssh 'systemctl is-enabled -q nfs-server || systemctl enable -q --now nfs-server' \
        || { error "  could not enable nfs-server on ${INSTANCE}"; return 1; }
}

# pn_ssh_stdin <command> — pn_ssh that passes stdin through (pn_ssh uses -n).
pn_ssh_stdin() {
    ssh -o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=accept-new \
        -o PasswordAuthentication=no -o KbdInteractiveAuthentication=no -o LogLevel=ERROR \
        "root@${ADDRESS}" "$@"
}

# nfs_node_pool_exists <pool>
nfs_node_pool_exists() { pn_ssh "zpool list -H -o name '$1' >/dev/null 2>&1"; }

# nfs_node_ensure_parent <pool> — <pool>/tappaas-nfs, explicitly sharenfs=off so no
# export is ever shared by inheritance (D4a).
nfs_node_ensure_parent() {
    local ds="$1/${NFS_PARENT}"
    pn_ssh "zfs list -H -o name '${ds}' >/dev/null 2>&1 || zfs create -o sharenfs=off '${ds}'" \
        || { error "  could not create ${ds} on ${INSTANCE}"; return 1; }
    [[ "$(pn_ssh "zfs get -H -o value,source sharenfs '${ds}'")" == $'off\tlocal' ]] \
        || pn_ssh "zfs set sharenfs=off '${ds}'"
}

# nfs_node_ensure_dataset <export-json> <uid> <gid> — create the export's dataset if
# absent, then assert quota, properties, and its root's owner and mode.
nfs_node_ensure_dataset() {
    local e="$1" uid="$2" gid="$3" pool name ds quota props mnt
    pool="$(jq -r .pool <<< "${e}")"; name="$(jq -r .name <<< "${e}")"
    ds="$(nfs_dataset "${pool}" "${name}")"
    quota="$(jq -r '.quota // "none"' <<< "${e}")"
    local want_mnt="${NFS_MOUNT_ROOT}/${name}"
    if ! pn_ssh "zfs list -H -o name '${ds}' >/dev/null 2>&1"; then
        pn_ssh "zfs create -o sharenfs=off -o mountpoint='${want_mnt}' '${ds}'" \
            || { error "  could not create ${ds} on ${INSTANCE}"; return 1; }
        info "  ${GN}✓${CL} created ${BL}${ds}${CL} at ${want_mnt}"
    fi
    # The same path on every node, whatever the pool (D2b): a share that moves
    # keeps the path its consumers mount. A dataset built before v0.8 is moved here
    # (a remount — an active client sees it as a brief stall).
    if [[ "$(pn_ssh "zfs get -H -o value mountpoint '${ds}'")" != "${want_mnt}" ]]; then
        pn_ssh "zfs set mountpoint='${want_mnt}' '${ds}'" || { error "  could not move ${ds} to ${want_mnt}"; return 1; }
        info "  ${GN}✓${CL} ${ds}: mounted at ${want_mnt}"
    fi
    # Quota: a value below what is already used is refused, never applied (D7).
    local cur used
    cur="$(pn_ssh "zfs get -H -p -o value quota '${ds}'")"
    if [[ "${quota}" == "none" ]]; then
        [[ "${cur}" == "0" ]] || pn_ssh "zfs set quota=none '${ds}'"
    else
        local want
        want="$(pn_ssh "numfmt --from=iec '${quota%B}'" 2>/dev/null)" \
            || { error "  ${ds}: quota '${quota}' is not a size"; return 1; }
        if [[ "${cur}" != "${want}" ]]; then
            used="$(pn_ssh "zfs get -H -p -o value used '${ds}'")"
            if (( want < used )); then
                error "  ${ds}: quota ${quota} is below what is already used — refused (ADR-029 D7)"; return 1
            fi
            pn_ssh "zfs set quota='${quota}' '${ds}'" || { error "  could not set quota on ${ds}"; return 1; }
            info "  ${GN}✓${CL} ${ds}: quota ${quota}"
        fi
    fi
    # Properties from the allow-list only (nfs_check_export refused the rest).
    while IFS=$'\t' read -r k v; do
        [[ -n "${k}" ]] || continue
        [[ "$(pn_ssh "zfs get -H -o value '${k}' '${ds}'")" == "${v}" ]] && continue
        pn_ssh "zfs set '${k}=${v}' '${ds}'" || { error "  could not set ${k}=${v} on ${ds}"; return 1; }
        info "  ${GN}✓${CL} ${ds}: ${k}=${v} (applies to blocks written from now on)"
    done < <(jq -r '.properties // {} | to_entries[] | "\(.key)\t\(.value)"' <<< "${e}")
    # The root belongs to the export's owner, 0770: every client is squashed to it.
    mnt="$(pn_ssh "zfs get -H -o value mountpoint '${ds}'")"
    pn_ssh "[ \"\$(stat -c '%u:%g:%a' '${mnt}')\" = '${uid}:${gid}:770' ] || { chown '${uid}:${gid}' '${mnt}' && chmod 0770 '${mnt}'; }" \
        || { error "  could not set the owner of ${mnt}"; return 1; }
}

# nfs_node_set_share <dataset> <value> — set sharenfs when it differs, then read the
# live export back: a zfs set with an option string libshare cannot parse succeeds
# on the property and fails only at share time (D4a).
nfs_node_set_share() {
    local ds="$1" want="$2" cur mnt live
    cur="$(pn_ssh "zfs get -H -o value sharenfs '${ds}'")"
    NFS_PREVIOUS_SHARE="${cur}"
    if [[ "${cur}" != "${want}" ]]; then
        pn_ssh "zfs set sharenfs='${want}' '${ds}'" || { error "  could not set sharenfs on ${ds}"; return 1; }
        info "  ${GN}✓${CL} ${ds}: sharenfs ${want}"
    fi
    mnt="$(pn_ssh "zfs get -H -o value mountpoint '${ds}'")"
    # exportfs -s: one "path client(options)" line per client, as exports(5) has it.
    live="$(pn_ssh "exportfs -s 2>/dev/null" | awk -v m="${mnt}" '$1 == m')"
    if [[ "${want}" == "off" ]]; then
        [[ -z "${live}" ]] || { error "  ${ds}: sharenfs is off but ${mnt} is still exported"; return 1; }
        return 0
    fi
    [[ -n "${live}" ]] || { error "  ${ds}: sharenfs is set but ${mnt} is not exported — check the option string ('${want}')"; return 1; }
    if grep -q 'no_root_squash' <<< "${live}" || ! grep -q 'root_squash' <<< "${live}" || ! grep -q 'all_squash' <<< "${live}"; then
        error "  ${ds}: the live export is not root- and all-squashed: ${live}"; return 1
    fi
}

# nfs_node_shared_datasets <pool> — every dataset under <pool>/tappaas-nfs, one name per line.
nfs_node_shared_datasets() {
    pn_ssh "zfs list -H -o name -r -d 1 '$1/${NFS_PARENT}' 2>/dev/null" | sed 1d
}

# nfs_consumer_address <consumer> — the consumer guest's current address, resolved
# the way every other module reaches it: <vmname>.<zone0>.internal through the
# site resolver. Empty when it does not resolve (not installed yet, or no lease).
nfs_consumer_address() {
    local cfg="${NFS_CONFIG_DIR}/$1.json" vmname zone
    [[ -f "${cfg}" ]] || return 0
    vmname="$(jq -r '.vmname // empty' "${cfg}")"; zone="$(jq -r '.zone0 // "mgmt"' "${cfg}")"
    [[ -n "${vmname}" ]] || return 0
    getent ahostsv4 "${vmname}.${zone}.internal" 2>/dev/null | awk 'NR == 1 {print $1}'
}

# nfs_node_reconcile — build and share every share declared for this node, then
# report (and unshare, never destroy) what is no longer declared for it. rc 1 when any export
# could not be brought to its declared state.
nfs_node_reconcile() {
    local e name pool uid gid rw ro c a grant ds p fails=0 problems
    local -A declared=()
    local -a exports=()
    local -a pools=()
    mapfile -t exports < <(nfs_exports "${INSTANCE}")
    if [[ "${#exports[@]}" -eq 0 ]]; then
        debug "  ${INSTANCE}: no shares declared for it"
    else
        info "${BOLD}nfs: ${#exports[@]} share(s) on ${BL}${INSTANCE}${CL}"
        nfs_node_ensure_server || return 1
    fi
    for e in "${exports[@]}"; do
        name="$(jq -r .name <<< "${e}")"; pool="$(jq -r '.pool // empty' <<< "${e}")"
        if problems="$(nfs_check_export "${e}" managed)"; then :; else
            while IFS= read -r p; do error "  ${p}"; done <<< "${problems}"
            fails=$((fails + 1)); continue
        fi
        if ! nfs_node_pool_exists "${pool}"; then
            error "  export ${name}: ${INSTANCE} has no pool '${pool}'"; fails=$((fails + 1)); continue
        fi
        ds="$(nfs_dataset "${pool}" "${name}")"; declared["${ds}"]=1
        [[ " ${pools[*]} " == *" ${pool} "* ]] || pools+=("${pool}")
        uid="$(jq -r '.owner.uid // empty' <<< "${e}")"; gid="$(jq -r '.owner.gid // empty' <<< "${e}")"
        if [[ -z "${uid}" || -z "${gid}" ]]; then
            # storage-manager allocates the owner when the share is added (D5, D17).
            error "  share ${name}: no owner in shares.json — declare it with storage-manager, which allocates one"
            fails=$((fails + 1)); continue
        fi
        nfs_node_ensure_parent "${pool}" && nfs_node_ensure_dataset "${e}" "${uid}" "${gid}" \
            || { fails=$((fails + 1)); continue; }
        # The client list (D5 layer 3, D16): see nfs_node_clients.
        rw=""; ro=""
        while read -r c grant a; do
            [[ -n "${c}" ]] || continue
            if [[ "${a}" == "-" ]]; then info "  share ${name}: ${c} mounts it but is not resolvable yet — not shared to it"; continue; fi
            if [[ "${grant}" == "rw" ]]; then rw+=" ${a}"; else ro+=" ${a}"; fi
        done < <(nfs_node_clients "${e}")
        nfs_node_set_share "${ds}" "$(nfs_render_sharenfs "${uid}" "${gid}" "${rw}" "${ro}")" \
            || fails=$((fails + 1))
    done
    # What is no longer declared is unshared and KEPT (D6): only an explicit purge
    # destroys data. Every pool the node has is checked, not just the declared ones,
    # so removing a node's last export on a pool still unshares it.
    local orphan
    while IFS= read -r p; do
        [[ -n "${p}" ]] || continue
        while IFS= read -r orphan; do
            [[ -n "${orphan}" && -z "${declared[${orphan}]:-}" ]] || continue
            if [[ "$(pn_ssh "zfs get -H -o value sharenfs '${orphan}'")" != "off" ]]; then
                pn_ssh "zfs set sharenfs=off '${orphan}'" && info "  ${orphan}: no longer declared — unshared, data kept"
            fi
            warn "  ${orphan}: an orphan (no share declares it here) — its data is kept; 'storage-manager nfs share purge ${orphan##*/}' destroys it"
        done < <(nfs_node_shared_datasets "${p}")
    done < <(pn_ssh "zpool list -H -o name")
    (( fails == 0 ))
}

# nfs_node_clients <export-json> — "<consumer> <access> <address>" per consumer that
# belongs in the export's client list (D5 layer 3, D16): granted, deployed, mounting
# this share, and not being deleted (NFS_EXCLUDE_CONSUMERS). Never a grant alone. An
# address that does not resolve yet prints as "-".
nfs_node_clients() {
    local e="$1" name c grant a
    name="$(jq -r .name <<< "${e}")"
    while IFS=$'\t' read -r c grant; do
        [[ -n "${c}" ]] || continue
        [[ " ${NFS_EXCLUDE_CONSUMERS:-} " == *" ${c} "* ]] && continue
        nfs_is_instance "${c}" || continue
        nfs_mounts_share "${c}" "${name}" || continue
        a="$(nfs_consumer_address "${c}")"
        printf '%s %s %s\n' "${c}" "${grant}" "${a:--}"
    done < <(jq -r '.grants // {} | to_entries[] | "\(.key)\t\(.value)"' <<< "${e}")
}

# nfs_node_expected_share <export-json> — the sharenfs value the export should carry
# now; the reconcile sets it, and the node's test compares the live value with it.
nfs_node_expected_share() {
    local e="$1" uid gid rw="" ro="" c grant a
    uid="$(jq -r '.owner.uid // empty' <<< "${e}")"; gid="$(jq -r '.owner.gid // empty' <<< "${e}")"
    while read -r c grant a; do
        [[ -n "${c}" && "${a}" != "-" ]] || continue
        if [[ "${grant}" == "rw" ]]; then rw+=" ${a}"; else ro+=" ${a}"; fi
    done < <(nfs_node_clients "${e}")
    nfs_render_sharenfs "${uid}" "${gid}" "${rw}" "${ro}"
}

# nfs_node_subdir <share> <subdir> — the subdir exists inside the share, owned by the
# share's owner, mode 0770 (D15). Prints "created" when it was made.
nfs_node_subdir() {
    local e uid gid dir
    e="$(nfs_export "${INSTANCE}" "$1")" || { error "  share $1 is not declared for ${INSTANCE}"; return 1; }
    uid="$(jq -r '.owner.uid // empty' <<< "${e}")"; gid="$(jq -r '.owner.gid // empty' <<< "${e}")"
    [[ -n "${uid}" ]] || { error "  share $1 has no owner yet"; return 1; }
    dir="${NFS_MOUNT_ROOT}/$1/$2"
    pn_ssh "[ -d '${dir}' ] || { install -d -o '${uid}' -g '${gid}' -m 0770 '${dir}' && echo created; }"
}

# nfs_node_purge <share> — destroy an orphan's dataset (D6, D17 `share purge`). Refused
# while shares.json still declares the share for this node, and while it is shared.
nfs_node_purge() {
    local name="$1" ds
    nfs_export "${INSTANCE}" "${name}" >/dev/null \
        && { error "  share ${name} is still declared for ${INSTANCE} — delete the declaration first"; return 1; }
    ds="$(pn_ssh "zfs list -H -o name,mountpoint 2>/dev/null | awk -v m='${NFS_MOUNT_ROOT}/${name}' '\$2 == m {print \$1}'")"
    [[ -n "${ds}" ]] || { info "  ${INSTANCE}: no dataset for share ${name} — nothing to purge"; return 0; }
    [[ "$(pn_ssh "zfs get -H -o value sharenfs '${ds}'")" == "off" ]] \
        || { error "  ${ds} is still shared — converge first"; return 1; }
    pn_ssh "exportfs -ra 2>/dev/null; for i in 1 2 3 4 5 6; do zfs destroy -r '${ds}' 2>/dev/null && exit 0; sleep 5; done; exit 1" \
        || { error "  could not destroy ${ds} (busy?)"; return 1; }
    pn_ssh "rmdir '${NFS_MOUNT_ROOT}/${name}' 2>/dev/null; true"
    info "  ${GN}✓${CL} ${ds} destroyed — share ${name}'s data is gone"
}
