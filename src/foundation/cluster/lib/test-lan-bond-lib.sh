#!/usr/bin/env bash
# Unit tests for lan-bond-lib.sh (#40): the lan bridge's uplink as a bond.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lan-bond-lib.sh
. "${HERE}/lan-bond-lib.sh"
pass=0; fail=0
check() { if [[ "$2" == "$3" ]]; then pass=$((pass+1)); else fail=$((fail+1)); printf '  FAIL: %s\n--- got\n%s\n--- want\n%s\n' "$1" "$2" "$3"; fi; }

check "one port is single"                 "$(lb_mode 1)"                 "single"
check "two ports default to active-backup" "$(lb_mode 2)"                 "active-backup"
check "lacp when asked"                    "$(lb_mode 2 lacp)"            "lacp"
lb_mode 1 lacp 2>/dev/null && r=accepted || r=refused
check "lacp on one port is refused"        "${r}"                         "refused"
lb_mode 2 bogus 2>/dev/null && r=accepted || r=refused
check "an unknown mode is refused"         "${r}"                         "refused"

check "comma list"                         "$(lb_ports enp1s0f0,enp1s0f1)" "enp1s0f0 enp1s0f1"
lb_ports a,a 2>/dev/null && r=accepted || r=refused
check "a port named twice is refused"      "${r}"                         "refused"
check "one port is its own bridge port"    "$(lb_bridge_port eno1)"       "eno1"
check "two ports bridge the bond"          "$(lb_bridge_port 'a b')"      "lanbond"

fake_speed() { case "$1" in tg0|tg1) echo 10000 ;; ge0) echo 1000 ;; *) echo -1 ;; esac; }
LB_SPEED_CMD=fake_speed
check "the fast port is primary"           "$(lb_default_primary 'ge0 tg0')" "tg0"
check "a tie keeps the first named"        "$(lb_default_primary 'tg1 tg0')" "tg1"
lb_equal_speeds 'tg0 tg1' && r=equal || r=unequal
check "two 10G ports are equal"            "${r}"                         "equal"
lb_equal_speeds 'tg0 ge0' 2>/dev/null && r=equal || r=unequal
check "10G + 1G is not"                    "${r}"                         "unequal"

check "single has no bond stanza"          "$(lb_bond_stanza eno1 single '')" ""
check "lacp stanza" "$(lb_bond_stanza 'tg0 tg1' lacp '')" "$(printf 'auto lanbond\niface lanbond inet manual\n\tbond-slaves tg0 tg1\n\tbond-miimon 100\n\tbond-mode 802.3ad\n\tbond-lacp-rate fast\n\tbond-xmit-hash-policy layer2+3')"
check "active-backup stanza with primary and mtu" "$(lb_bond_stanza 'tg0 ge0' active-backup tg0 9000)" "$(printf 'auto lanbond\niface lanbond inet manual\n\tbond-slaves tg0 ge0\n\tbond-miimon 100\n\tbond-mode active-backup\n\tbond-primary tg0\n\tmtu 9000')"

# The file config-network.sh writes for a secondary node, after the cutover.
ORIG="$(cat <<'EOF'
# network interface settings; generated by TAPPaaS config-network.sh
auto lo
iface lo inet loopback

iface tg0 inet manual
iface tg1 inet manual
iface ge0 inet manual

auto wan
iface wan inet manual
	bridge-ports ge0
	bridge-stp off
	bridge-fd 0
	post-up ip route add 192.168.1.0/24 via 192.168.2.1 || true

auto lan
iface lan inet static
	address 10.0.0.11/24
	gateway 10.0.0.1
	bridge-ports tg0
	bridge-stp off
	bridge-fd 0
	bridge-vlan-aware yes
	bridge-vids 2-4094
EOF
)"

stanza="$(lb_bond_stanza 'tg0 tg1' lacp '')"
BONDED="$(lb_set_lan lanbond "${stanza}" <<<"${ORIG}")"
want="$(sed 's/^\tbridge-ports tg0$/\tbridge-ports lanbond/' <<<"${ORIG}" \
    | S="${stanza}" awk '/^auto lan$/ { printf "%s\n\n", ENVIRON["S"] } { print }')"
check "bonding inserts the stanza before lan and repoints the bridge" "${BONDED}" "${want}"

check "rewriting with the same bond is a no-op" "$(lb_set_lan lanbond "${stanza}" <<<"${BONDED}")" "${BONDED}"

stanza2="$(lb_bond_stanza 'tg0 ge0' active-backup tg0 '')"
AB="$(lb_set_lan lanbond "${stanza2}" <<<"${BONDED}")"
check "a changed bond replaces the old stanza, once" "$(grep -c '^iface lanbond' <<<"${AB}")" "1"
check "…with the new members"              "$(grep 'bond-slaves' <<<"${AB}")" $'\tbond-slaves tg0 ge0'
check "wan and its route are untouched"    "$(sed -n '/^auto wan/,/^$/p' <<<"${AB}")" "$(sed -n '/^auto wan/,/^$/p' <<<"${ORIG}")"

check "back to one port restores the original" "$(lb_set_lan tg0 '' <<<"${BONDED}")" "${ORIG}"

MTU="$(lb_set_lan lanbond "$(lb_bond_stanza 'tg0 tg1' lacp '' 9000)" 9000 <<<"${ORIG}")"
check "mtu is set on lan"                  "$(sed -n '/^iface lan /,$p' <<<"${MTU}" | grep -c $'^\tmtu 9000$')" "1"
check "mtu set twice stays one line"       "$(lb_set_lan lanbond "$(lb_bond_stanza 'tg0 tg1' lacp '' 9000)" 9000 <<<"${MTU}" | sed -n '/^iface lan /,$p' | grep -c 'mtu')" "1"

NOWAN="$(lb_wan_none <<<"${ORIG}")"
check "no-wan: wan keeps its stanza, without its port" "$(sed -n '/^iface wan/,/^$/p' <<<"${NOWAN}" | grep bridge-ports)" $'\tbridge-ports none'
check "no-wan: the route on wan stays"   "$(grep -c 'post-up ip route' <<<"${NOWAN}")" "1"
check "no-wan: lan untouched"            "$(sed -n '/^iface lan/,$p' <<<"${NOWAN}")" "$(sed -n '/^iface lan/,$p' <<<"${ORIG}")"
check "ge0 moves from wan into the bond" "$(lb_set_lan lanbond "$(lb_bond_stanza 'tg0 ge0' active-backup tg0 '')" <<<"${NOWAN}" | grep -c 'bridge-ports ge0')" "0"

WANP="$(lb_wan_port ge1 <<<"${NOWAN}")"
check "wan-port: wan carries the port again" "$(sed -n '/^iface wan/,/^$/p' <<<"${WANP}" | grep bridge-ports)" $'\tbridge-ports ge1'
check "wan-port: lan untouched"          "$(sed -n '/^iface lan/,$p' <<<"${WANP}")" "$(sed -n '/^iface lan/,$p' <<<"${NOWAN}")"
check "wan-port: the route on wan stays" "$(grep -c 'post-up ip route' <<<"${WANP}")" "1"

echo "Results: ${pass} passed, ${fail} failed"
[[ ${fail} -eq 0 ]]
